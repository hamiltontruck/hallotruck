const pairMaps = {
  so: new Map(translations.so),
  ti: new Map(translations.ti),
};

const orderedPairs = {
  so: [...translations.so].sort((a, b) => b[0].length - a[0].length),
  ti: [...translations.ti].sort((a, b) => b[0].length - a[0].length),
};

function isTechnicalValue(value: string) {
  return /^(?:HT-[A-Z0-9-]+|[+\d][\d\s().-]*|[A-Z0-9_-]{8,}|\d+(?:[.,]\d+)?\s*(?:ETB|km|m|t|MB|%|min)?)$/i.test(value);
}

function translateCore(value: string, language: RuntimePageLanguage) {
  const direct = pairMaps[language].get(value);
  if (direct) return direct;
  if (isTechnicalValue(value)) return value;

  let translated = value;
  for (const [source, target] of orderedPairs[language]) {
    if (source.length < 8 || !source.includes(" ") || !translated.includes(source)) continue;
    translated = translated.split(source).join(target);
  }
  return translated;
}

function translatePreservingWhitespace(value: string, language: RuntimePageLanguage) {
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const core = value.slice(leading.length, value.length - trailing.length);
  if (!core) return value;
  return `${leading}${translateCore(core, language)}${trailing}`;
}

function shouldSkipText(node: Text) {
  const parent = node.parentElement;
  return !parent || Boolean(parent.closest("script, style, code, pre, textarea, [data-no-runtime-translate]"));
}

function processText(node: Text, language: RuntimePageLanguage | null) {
  if (shouldSkipText(node)) return;
  const current = node.nodeValue ?? "";
  const previous = textState.get(node);

  if (!language) {
    if (previous && current === previous.translated) node.nodeValue = previous.source;
    textState.delete(node);
    return;
  }

  const source = previous && current === previous.translated ? previous.source : current;
  const translated = translatePreservingWhitespace(source, language);
  if (translated === source) {
    textState.delete(node);
    return;
  }

  textState.set(node, { source, translated });
  if (current !== translated) node.nodeValue = translated;
}

function processAttribute(element: Element, attribute: string, language: RuntimePageLanguage | null) {
  if (element.closest("[data-no-runtime-translate]")) return;
  const current = element.getAttribute(attribute);
  if (current === null) return;

  const states = attributeState.get(element) ?? new Map<string, AttributeState>();
  const previous = states.get(attribute);

  if (!language) {
    if (previous && current === previous.translated) element.setAttribute(attribute, previous.source);
    states.delete(attribute);
    if (states.size) attributeState.set(element, states);
    else attributeState.delete(element);
    return;
  }

  const source = previous && current === previous.translated ? previous.source : current;
  const translated = translatePreservingWhitespace(source, language);
  if (translated === source) {
    states.delete(attribute);
    if (states.size) attributeState.set(element, states);
    else attributeState.delete(element);
    return;
  }

  states.set(attribute, { source, translated });
  attributeState.set(element, states);
  if (current !== translated) element.setAttribute(attribute, translated);
}

function processElement(element: Element, language: RuntimePageLanguage | null) {
  for (const attribute of translatedAttributes) processAttribute(element, attribute, language);
}

function localizeTree(root: Node, language: RuntimePageLanguage | null) {
  if (root.nodeType === Node.TEXT_NODE) {
    processText(root as Text, language);
    return;
  }

  if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_FRAGMENT_NODE && root.nodeType !== Node.DOCUMENT_NODE) return;
  if (root.nodeType === Node.ELEMENT_NODE) processElement(root as Element, language);

  const textWalker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let textNode = textWalker.nextNode();
  while (textNode) {
    processText(textNode as Text, language);
    textNode = textWalker.nextNode();
  }

  if ("querySelectorAll" in root) {
    (root as ParentNode).querySelectorAll("[placeholder], [aria-label], [title], [alt]").forEach((element) => processElement(element, language));
  }
}

export function useRuntimePageTranslation(language: RuntimePageLanguage | null) {
  useEffect(() => {
    const root = document.body;
    localizeTree(root, language);

    const observer = new MutationObserver((mutations) => {
      for (const mutation of mutations) {
        if (mutation.type === "characterData") {
          processText(mutation.target as Text, language);
          continue;
        }
        if (mutation.type === "attributes") {
          processAttribute(mutation.target as Element, mutation.attributeName ?? "", language);
          continue;
        }
        mutation.addedNodes.forEach((node) => localizeTree(node, language));
      }
    });

    observer.observe(root, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: [...translatedAttributes],
    });

    return () => {
      observer.disconnect();
      if (!language) localizeTree(root, null);
    };
  }, [language]);
}
