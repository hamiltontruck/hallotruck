import assert from "node:assert/strict";
import { readFile, readdir } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";

const db = new PGlite();
const id = n => `00000000-0000-4000-8000-${String(n).padStart(12,"0")}`;
const owner=id(1), admin=id(2), outsider=id(3), driver=id(4), partner=id(10), other=id(11);
await db.exec(`create role anon; create role authenticated; create schema auth; create schema private;
create function auth.uid() returns uuid language sql as $$select nullif(current_setting('test.actor',true),'')::uuid$$;
create function private.is_admin_or_ceo() returns boolean language sql as $$select auth.uid()='${admin}'::uuid$$;
create function private.require_active_leadership(text) returns void language plpgsql as $$begin if auth.uid() is distinct from '${admin}'::uuid then raise exception 'Admin or CEO access required'; end if; end$$;
create function private.normalize_public_mobile_phone(text) returns text language sql as $$select $1$$;
create table auth.users(id uuid primary key,email text,created_at timestamptz default now(),email_confirmed_at timestamptz);
create type public.driver_status as enum('pending','approved','suspended');
create table profiles(id uuid primary key,role text,full_name text,phone text,driver_status public.driver_status);
create table partner_organizations(id uuid primary key,name text,status text);
create table partner_memberships(partner_id uuid,user_id uuid,active boolean,member_role text);
create table partner_activity_log(partner_id uuid,actor_id uuid,action text,entity_type text,entity_id text,metadata jsonb);
create table trucks(id uuid primary key,partner_id uuid,driver_id uuid,status text,updated_at timestamptz);
create table orders(truck_id uuid,driver_id uuid,status text);
create table partner_fleet_vehicles(id uuid primary key,partner_id uuid,truck_id uuid,assigned_driver_id uuid,status text);
create table driver_verification_files(driver_id uuid,truck_id uuid,document_key text,status text,expiry_date date);
insert into partner_organizations values('${partner}','TEST Partner','active'),('${other}','OTHER Partner','active');
insert into profiles values('${owner}','partner','OWNER','0911111111',null),('${admin}','admin','ADMIN','0922222222',null),('${outsider}','partner','OTHER','0933333333',null);
insert into partner_memberships values('${partner}','${owner}',true,'owner'),('${other}','${outsider}',true,'owner');`);
const existingApproval=(await readFile('supabase/migrations/20260913195801_compact_driver_verification.sql','utf8')).match(/create or replace function public\.admin_approve_driver_onboarding[\s\S]*?grant execute on function public\.admin_approve_driver_onboarding\(uuid\) to authenticated;/)?.[0];
assert.ok(existingApproval,'actual document approval SQL must be available');
await db.exec(existingApproval);
const file = (await readdir('supabase/migrations')).find(name=>name.endsWith('_partner_driver_registration.sql'));
assert.ok(file, "Partner driver registration migration must exist");
await db.exec(await readFile(`supabase/migrations/${file}`,'utf8'));

await db.exec(`alter table profiles add column email text, add column home_address text;
alter table trucks add column plate_number text, add column vehicle_type text, add column capacity_tons numeric;
alter table orders add column id uuid default gen_random_uuid(), add column tracking_id text, add column pickup_address text, add column dropoff_address text, add column price_etb numeric, add column payment_terms text, add column cancellation_reason text, add column cancelled_at timestamptz, add column created_at timestamptz default now();`);
const actor = async who => db.query("select set_config('test.actor',$1,false)",[who??'']);
const migration = (await readdir('supabase/migrations')).find(n=>n.endsWith('_partner_driver_workspace_ownership.sql'));
assert.ok(migration,'Server-managed Partner ownership migration is required');
await db.exec(await readFile(`supabase/migrations/${migration}`,'utf8'));
await actor(owner);
const invitation=(await db.query("select create_partner_driver_registration($1,'TEST Driver','driver@example.test','0944444444') as value",[partner])).rows[0].value;
await db.query("insert into auth.users(id,email,created_at,email_confirmed_at) values($1,'driver@example.test',clock_timestamp(),now())",[driver]);
await db.query("insert into profiles(id,role,full_name,phone,driver_status) values($1,'driver','TEST Driver','0944444444','pending')",[driver]);
await actor(driver);
await db.query('select claim_partner_driver_registration($1)',[invitation.token]);
assert.equal((await db.query('select get_my_driver_workspace() as value')).rows[0].value.kind,'partner');
await db.query('select claim_partner_driver_registration($1)',[invitation.token]);
assert.equal((await db.query('select count(*)::int as n from partner_driver_ownership')).rows[0].n,1);
await db.query("update partner_driver_registrations set status='rejected' where id=$1",[invitation.id]);
assert.equal((await db.query('select get_my_driver_workspace() as value')).rows[0].value.kind,'partner','rejection retains ownership');
const hallo=id(6);
await db.query("insert into profiles(id,role,full_name,driver_status) values($1,'driver','HALLO Driver','approved')",[hallo]);
await db.query("insert into partner_fleet_vehicles(id,partner_id,assigned_driver_id,status) values($1,$2,$3,'inactive')",[id(25),partner,hallo]);
await actor(hallo);
assert.equal((await db.query('select get_my_driver_workspace() as value')).rows[0].value.kind,'hallo','historical fleet association does not transfer HALLO ownership');
await actor(admin);
assert.deepEqual((await db.query("select id from list_admin_driver_roster('hallo')")).rows.map(r=>r.id),[hallo]);
assert.deepEqual((await db.query("select id from list_admin_driver_roster('partner')")).rows.map(r=>r.id),[driver]);
await actor(owner);
assert.deepEqual((await db.query('select id from list_partner_driver_roster($1)',[partner])).rows.map(r=>r.id),[driver]);
await assert.rejects(db.query('select * from list_partner_driver_roster($1)',[other]),/owner or admin/);
await assert.rejects(db.query("select * from list_admin_driver_roster('hallo')"),/Admin or CEO/);
await actor(null);
await assert.rejects(db.query('select get_my_driver_workspace()'),/authentication/i);
assert.equal((await db.query("select has_table_privilege('authenticated','public.partner_driver_ownership','insert') as allowed")).rows[0].allowed,false);
assert.equal((await db.query("select has_function_privilege('anon','public.get_my_driver_workspace()','execute') as allowed")).rows[0].allowed,false);
await actor(driver);
await db.query("update partner_organizations set status='suspended' where id=$1",[partner]);
assert.equal((await db.query('select get_my_driver_workspace() as value')).rows[0].value.organization_active,false);
await db.close();
console.log('Partner ownership: disjoint rosters, atomic claim, rejected ownership, HALLO legacy fleet, ACL and inactive organization PASS');
