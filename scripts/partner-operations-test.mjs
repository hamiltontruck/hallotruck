import assert from 'node:assert/strict';
import {build} from 'esbuild';
const bundle=await build({entryPoints:['src/domain/partner-operations.ts'],bundle:true,write:false,platform:'node',format:'esm'});
const {partnerJobStage,filterPartnerDrivers,joinPartnerDrivers,isLocatedTrip,isActivePartnerInvitation}=await import(`data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString('base64')}`);
const job={id:'job',order_id:'order',partner_id:'p',status:'confirmed',selected_driver_id:'d',selected_truck_id:'t',order:{id:'order',status:'accepted',driver_id:'d',truck_id:'t'}};
assert.equal(partnerJobStage(job),'ready');
assert.equal(partnerJobStage({...job,order:{...job.order,status:'in_transit'}}),'in_transit');
assert.equal(partnerJobStage({...job,order:{...job.order,status:'delivered'}}),'delivered');
assert.equal(partnerJobStage({...job,status:'accepted',order:{...job.order,status:'placed',driver_id:null,truck_id:null}}),'awaiting_confirmation');
assert.equal(partnerJobStage({...job,status:'pending',order:{...job.order,status:'placed',driver_id:null,truck_id:null}}),'offered');
for(const status of ['rejected','cancelled'])assert.equal(partnerJobStage({...job,status}),'closed');
assert.equal(partnerJobStage({...job,order:null}),'unknown');
assert.equal(partnerJobStage({...job,order:{...job.order,driver_id:'other'}}),'unknown');
assert.equal(partnerJobStage({...job,status:'pending',order:{...job.order,status:'delivered'}}),'unknown');
for(const status of ['pending','accepted'])assert.equal(partnerJobStage({...job,status,order:{...job.order,status:'placed'}}),'unknown','Placed orders with an assignment are not available or waiting for confirmation');
const roster=[{id:'d',full_name:'Fami',driver_status:'approved',plate_number:'ET-001',email:'own@example.test'}];
const registrations=[{id:'r',driver_id:'d',full_name:'Fami',status:'registered'},{id:'i',driver_id:null,full_name:'New Driver',status:'invited',expires_at:'2099-01-01'}];
const rows=joinPartnerDrivers(roster,registrations);
assert.equal(rows.length,2);assert.equal(rows.filter(r=>r.driver?.driver_status==='approved').length,1);
assert.equal(filterPartnerDrivers(rows,'ET-001','all').length,1);
assert.equal(filterPartnerDrivers(rows,'new','invited').length,1);
assert.equal(filterPartnerDrivers(rows,'','approved').length,1);
assert.equal(filterPartnerDrivers(rows,'','pending').length,0);
assert.ok(isLocatedTrip({truck_lng:39,truck_lat:9}));
for(const [lng,lat] of [[null,null],[NaN,9],[181,9],[39,91],[Infinity,9]])assert.equal(isLocatedTrip({truck_lng:lng,truck_lat:lat}),false);
assert.equal(isActivePartnerInvitation({...registrations[1],expires_at:'2020-01-01'}),false);
assert.equal(isActivePartnerInvitation({...registrations[1],expires_at:'invalid'}),false);
assert.equal(isActivePartnerInvitation(registrations[1]),true);
console.log('Partner operations: canonical lifecycle, assignment mismatch, driver identity/search and GPS bounds PASS');
